import type { LevelSpec } from './LevelGrid';

function border(width: number): string {
  return '#'.repeat(width);
}

function row(width: number, fill: string, inner: Array<[number, string]> = []): string {
  const cells = new Array<string>(width).fill(fill);
  cells[0] = '#';
  cells[width - 1] = '#';
  for (const [x, glyph] of inner) cells[x] = glyph;
  return cells.join('');
}

